export async function getOrderReport(req, res) {
  const { orderNo, reportType } = req.query;

  const report = REPORTS[reportType];
  if (!report) {
    return res.status(400).json({
      error: `Invalid reportType. Valid values: ${Object.keys(REPORTS).join(", ")}`,
    });
  }

  let connection;

  try {
    connection = await getConnection();

    const result = await connection.execute(report.sql, {
      ORDERNO: orderNo,
    });

    const resp = mapRows(result.rows, report.fields);

    return res.json({
      statusCode: 0,
      data: resp,
    });
  } catch (err) {
    console.error(`Error retrieving ${reportType} data:`, err);

    return res.status(500).json({
      error: "Internal Server Error",
    });
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (e) {
        console.error("Error closing connection:", e);
      }
    }
  }
}
