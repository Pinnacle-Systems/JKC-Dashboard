/**
 * Map an oracledb rows array (array-of-arrays) into an array of objects
 * using the supplied field name list (positional).
 */
function mapRows(rows, fields) {
  return (rows || []).map((row) =>
    fields.reduce((obj, field, idx) => {
      obj[field] = row[idx];
      return obj;
    }, {}),
  );
}

